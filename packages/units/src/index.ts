export const MPaToKgfCm2=(v:number)=>v/0.0980665;
export const MPaToKPa=(v:number)=>v*1000;
export const mToMm=(v:number)=>v*1000;
export const kNToN=(v:number)=>v*1000;
export const kNmToNmm=(v:number)=>v*1e6;
export const mm2ToCm2=(v:number)=>v/100;
